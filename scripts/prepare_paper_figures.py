#!/usr/bin/env python3
"""
Generate and organize all research paper figures, architectural diagrams,
benchmark tables, confusion/detection plots, and visual assets into a
single clean directory: `paper_figures/`.
"""
import os, shutil, json
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

BASE_DIR = Path(__file__).resolve().parents[1]
OUT_DIR = BASE_DIR / "paper_figures"
OUT_DIR.mkdir(parents=True, exist_ok=True)

# ---------------------------------------------------------------------------
# 1. Copy and rename existing core system images
# ---------------------------------------------------------------------------
existing_assets = [
    ("data/raw/demo/media/RAG.png", "fig01_rag_system_concept.png", "System Overview & Tri-Modal Evidence Concept"),
    ("data/raw/demo/media/KG_neo4j.png", "fig02_knowledge_graph_traversal.png", "Knowledge Graph Node-Link Schema & Multi-hop Traversal"),
    ("data/raw/demo/media/KG_networkx.png", "fig03_topological_graph_network.png", "Topological Graph Network Extracted from P&ID"),
    ("data/raw/demo/data/0.png", "fig04_sample_pid_sheet_input.png", "High-Resolution Input P&ID Drawing (7168x4562 px)"),
    ("data/raw/demo/data/0_graph.png", "fig05_sheet_graph_overlay.png", "Extracted Graph Overlaid on Input Drawing Geometry"),
    ("data/raw/demo/media/one_shot_symbols.png", "fig06_pid_symbol_classes_atlas.png", "P&ID Symbol Ontology (Standard 32 Classes)"),
    ("scratch/ocr_fail.png", "fig07_ocr_failure_analysis_contact_sheet.png", "OCR Diagnostic Analysis (Vertical Tags & Clipped Prefixes)"),
    ("runs/pid_512/labels_correlogram.jpg", "fig08_yolo_labels_correlogram.jpg", "YOLOv8 Bounding Box Spatial & Scale Distribution"),
    ("runs/pid_512/train_batch0.jpg", "fig09_yolo_train_batch_samples.jpg", "YOLOv8 Training Tiles with Multi-Class Ground Truth"),
    ("data/uploads/u_offshore_landscape_p1_60e11e.png", "fig10_real_offshore_drawing_pfd.png", "Real Industrial Offshore Drawing: Alpha Field Gas Treatment PFD"),
    ("data/uploads/u_pid_real_p1_52af52.png", "fig11_real_offshore_production_pid.png", "Real Industrial Offshore Drawing: LP Compressor Suction Cooler P&ID"),
    ("data/uploads/u_rig_three_stage_separation_and_gas_c.png", "fig12_rig_builder_procedural_pid.png", "Procedurally Synthesized P&ID Generated by Rig Builder"),
]

copied_manifest = []
for rel_src, dest_name, label in existing_assets:
    src_path = BASE_DIR / rel_src
    if src_path.exists():
        dest_path = OUT_DIR / dest_name
        shutil.copy2(src_path, dest_path)
        copied_manifest.append((dest_name, label, str(rel_src)))
        print(f"Copied: {rel_src} -> {dest_name}")
    else:
        print(f"Notice: {rel_src} not found, skipping copy.")

# Styling configuration for publication-ready matplotlib figures
plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
plt.rcParams.update({
    "font.family": "sans-serif",
    "font.size": 11,
    "axes.titlesize": 13,
    "axes.labelsize": 11,
    "xtick.labelsize": 10,
    "ytick.labelsize": 10,
    "figure.titlesize": 15,
    "figure.dpi": 300,
    "savefig.dpi": 300,
    "savefig.bbox": "tight",
})

# ---------------------------------------------------------------------------
# 2. Generate Figure: System Architecture Block Diagram
# ---------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(13, 6))
ax.axis("off")

boxes = [
    ("Stage 1\nAdaptive Tiling", "54 Tiles (1024x1024)\nStride 768px (25% overlap)\nNative Scale Preserved", (0.02, 0.55)),
    ("Stage 2\nSymbol Detection", "YOLOv8s @ 512px\nConf 0.88, NMS IoU 0.20\nGlobal Coord Remapping", (0.18, 0.55)),
    ("Stage 3\nDual-Orientation OCR", "PaddleOCR (0° and -90°)\nCrop Upscaling (3x)\nBipartite Hungarian Matching", (0.35, 0.55)),
    ("Stage 4\nTopology Tracing", "Symbol Masking (pad=20)\nInk Skeletonization\nMinimum Spanning Tree (MST)", (0.52, 0.55)),
    ("Stage 5\nSemantic Inference", "7-Rule Flow Propagation\nISA-5.1 Tag Decoding\nControl Loops (CONTROLS)", (0.69, 0.55)),
    ("Stage 6\nEmbedded KG (Kùzu)", "1,948 Symbols, 2,043 Edges\nZero Docker / JVM (~50MB)\nSingle-Writer / Read Replicas", (0.86, 0.55)),
]

for title, desc, (x, y) in boxes:
    ax.text(x + 0.06, y + 0.22, title, ha="center", va="center", weight="bold",
            bbox=dict(boxstyle="square,pad=0.6", facecolor="#1E293B", edgecolor="#0EA5E9", lw=1.5),
            color="#FFFFFF", fontsize=11)
    ax.text(x + 0.06, y + 0.05, desc, ha="center", va="center",
            bbox=dict(boxstyle="round,pad=0.5", facecolor="#F8FAFC", edgecolor="#CBD5E1", lw=1),
            color="#334155", fontsize=8.5)

# Arrows between stages
for i in range(len(boxes) - 1):
    x1 = boxes[i][2][0] + 0.12
    x2 = boxes[i+1][2][0]
    ax.annotate("", xy=(x2, 0.65), xytext=(x1, 0.65),
                arrowprops=dict(arrowstyle="->", color="#0284C7", lw=2.5))

# Query Pipeline below
query_boxes = [
    ("Natural Language\nQuery", "\"What valves isolate\npump P-101?\"", (0.08, 0.12)),
    ("TF-IDF Few-Shot\nSelector", "Word+Char n-grams (0.2s)\nRetrieves 3 solved\nCypher templates", (0.28, 0.12)),
    ("NL-to-Cypher\n(Qwen 8B)", "Dynamic Tag Injection\nSchema Grounding\nAST Repair Loop", (0.48, 0.12)),
    ("Tri-Modal Answer\nGrounding", "1. Cypher Graph Path\n2. Visual Bounding Box Crops\n3. Spec Manual Citations", (0.75, 0.12)),
]

for title, desc, (x, y) in query_boxes:
    ax.text(x + 0.07, y + 0.12, title, ha="center", va="center", weight="bold",
            bbox=dict(boxstyle="square,pad=0.5", facecolor="#0F172A", edgecolor="#10B981", lw=1.5),
            color="#FFFFFF", fontsize=10)
    ax.text(x + 0.07, y - 0.03, desc, ha="center", va="center",
            bbox=dict(boxstyle="round,pad=0.5", facecolor="#F0FDF4", edgecolor="#A7F3D0", lw=1),
            color="#065F46", fontsize=8.5)

for i in range(len(query_boxes) - 1):
    x1 = query_boxes[i][2][0] + 0.14
    x2 = query_boxes[i+1][2][0]
    ax.annotate("", xy=(x2, 0.18), xytext=(x1, 0.18),
                arrowprops=dict(arrowstyle="->", color="#059669", lw=2))

# Connect KG to NL Engine
ax.annotate("", xy=(0.86, 0.45), xytext=(0.82, 0.25),
            arrowprops=dict(arrowstyle="<->", color="#6366F1", lw=2, linestyle="dashed"))
ax.text(0.88, 0.35, "Cypher\nExecution", color="#4338CA", weight="bold", fontsize=9)

plt.title("Figure 1: End-to-End System Architecture of Engineering Drawing Intelligence (EDI)",
          pad=20, weight="bold", color="#0F172A")
plt.savefig(OUT_DIR / "fig13_complete_system_architecture.png")
plt.close()
print("Generated fig13_complete_system_architecture.png")

# ---------------------------------------------------------------------------
# 3. Generate Figure: Per-Sheet Detection Performance (from reports/detection.json)
# ---------------------------------------------------------------------------
det_json_path = BASE_DIR / "reports" / "detection.json"
if det_json_path.exists():
    with open(det_json_path) as f:
        det_data = json.load(f)
    
    sheets = [d["sheet"] for d in det_data["per_sheet"]]
    precisions = [d["precision"] * 100 for d in det_data["per_sheet"]]
    recalls = [d["recall"] * 100 for d in det_data["per_sheet"]]
    f1s = [2 * (p * r) / (p + r) if (p + r) > 0 else 0 for p, r in zip(precisions, recalls)]
    
    x = np.arange(len(sheets))
    width = 0.28
    
    fig, ax = plt.subplots(figsize=(14, 5.5))
    rects1 = ax.bar(x - width, precisions, width, label="Precision", color="#3B82F6")
    rects2 = ax.bar(x, recalls, width, label="Recall", color="#10B981")
    rects3 = ax.bar(x + width, f1s, width, label="F1 Score", color="#6366F1")
    
    ax.set_ylabel("Score (%)", weight="bold")
    ax.set_xlabel("Test Sheet ID (PIDQA Unseen Evaluation Sheets)", weight="bold")
    ax.set_title("Figure 2: Micro-Symbol Detection Metrics per Sheet (YOLOv8s @ 512px, 20 Unseen Sheets, N=2,311)",
                 weight="bold", pad=15)
    ax.set_xticks(x)
    ax.set_xticklabels(sheets)
    ax.set_ylim(92, 101)
    ax.axhline(det_data["f1"] * 100, color="#DC2626", linestyle="--", lw=1.5,
               label=f"Overall F1 ({det_data['f1']*100:.2f}%)")
    ax.legend(loc="lower right", frameon=True)
    plt.savefig(OUT_DIR / "fig14_detection_metrics_per_sheet.png")
    plt.close()
    print("Generated fig14_detection_metrics_per_sheet.png")

# ---------------------------------------------------------------------------
# 4. Generate Figure: Benchmark Breakdown (Real Detector vs Ceiling)
# ---------------------------------------------------------------------------
categories = ["Simple Counting", "Spatial Connection", "Spatial Counting", "Value / Tags", "OVERALL"]
n_counts = [544, 544, 544, 544, 2176]
real_scores = [0.9908 * 100, 0.8879 * 100, 0.7923 * 100, 0.5441 * 100, 0.8038 * 100]
ceiling_scores = [1.0000 * 100, 0.9044 * 100, 0.7941 * 100, 0.7463 * 100, 0.8612 * 100]

x = np.arange(len(categories))
width = 0.35

fig, ax = plt.subplots(figsize=(10, 5.5))
rects1 = ax.bar(x - width/2, real_scores, width, label="End-to-End (Real Trained Detector)", color="#2563EB")
rects2 = ax.bar(x + width/2, ceiling_scores, width, label="Ablation Ceiling (Ground-Truth Detector)", color="#94A3B8")

ax.set_ylabel("Accuracy (%)", weight="bold")
ax.set_title("Figure 3: PIDQA Benchmark Accuracy by Query Category (2,176 Questions, 17 Sheets)",
             weight="bold", pad=15)
ax.set_xticks(x)
ax.set_xticklabels([f"{cat}\n(N={n})" for cat, n in zip(categories, n_counts)], weight="bold")
ax.set_ylim(40, 105)

for rect in rects1:
    h = rect.get_height()
    ax.annotate(f"{h:.1f}%", xy=(rect.get_x() + rect.get_width()/2, h),
                xytext=(0, 3), textcoords="offset points", ha="center", va="bottom",
                fontsize=9.5, weight="bold", color="#1E3A8A")

for rect in rects2:
    h = rect.get_height()
    ax.annotate(f"{h:.1f}%", xy=(rect.get_x() + rect.get_width()/2, h),
                xytext=(0, 3), textcoords="offset points", ha="center", va="bottom",
                fontsize=9.5, color="#475569")

ax.legend(loc="lower left", frameon=True)
plt.savefig(OUT_DIR / "fig15_pidqa_benchmark_accuracies.png")
plt.close()
print("Generated fig15_pidqa_benchmark_accuracies.png")

# ---------------------------------------------------------------------------
# 5. Generate Figure: Detection Threshold Tuning Ablation (IoU & Conf)
# ---------------------------------------------------------------------------
configs = [
    "Ultralytics Default\n(Conf 0.25, NMS IoU 0.55)",
    "Intermediate Tuning\n(Conf 0.70, NMS IoU 0.40)",
    "Optimized EDI\n(Conf 0.88, NMS IoU 0.20)",
]
f1_thresholds = [0.820 * 100, 0.916 * 100, 0.993 * 100]

fig, ax = plt.subplots(figsize=(8, 5))
bars = ax.bar(configs, f1_thresholds, color=["#F87171", "#FBBF24", "#34D399"], width=0.55)
ax.set_ylabel("Full-Sheet F1 Score (%)", weight="bold")
ax.set_title("Figure 4: Impact of NMS IoU & Confidence Tuning on Overlapping Tile Detection",
             weight="bold", pad=15)
ax.set_ylim(70, 105)

for bar in bars:
    yval = bar.get_height()
    ax.text(bar.get_x() + bar.get_width()/2, yval + 1, f"{yval:.1f}%",
            ha="center", va="bottom", weight="bold", fontsize=11)

ax.text(0, 75, "Severe duplicate overcounting\ndue to tile stride overlap", ha="center", style="italic", fontsize=9, color="#991B1B")
ax.text(2, 75, "Eliminates duplicate seam boxes\nacross 54 tiles/sheet", ha="center", style="italic", fontsize=9, color="#065F46")

plt.savefig(OUT_DIR / "fig16_threshold_tuning_ablation.png")
plt.close()
print("Generated fig16_threshold_tuning_ablation.png")

# ---------------------------------------------------------------------------
# 6. Generate Figure: Pipeline Runtime Latency Breakdown
# ---------------------------------------------------------------------------
stages = [
    "Preprocessing\n& Tiling",
    "YOLOv8\nDetection",
    "OCR Text\nRecognition",
    "Line Tracing\n& Topology",
    "Graph Build\n(Kùzu)",
    "NL-to-Cypher\n(LLM)",
]
times = [0.06, 3.0, 75.0, 0.35, 0.25, 5.0]  # seconds per sheet / query

fig, ax = plt.subplots(figsize=(9, 4.5))
bars = ax.barh(stages[::-1], times[::-1], color="#38BDF8")
ax.set_xlabel("Execution Time (seconds, log scale)", weight="bold")
ax.set_xscale("log")
ax.set_title("Figure 5: Computational Latency Breakdown across Pipeline Stages (Apple M3 Pro)",
             weight="bold", pad=15)

for bar in bars:
    w = bar.get_width()
    ax.text(w * 1.15, bar.get_y() + bar.get_height()/2, f"{w:.2f} s",
            ha="left", va="center", weight="bold", fontsize=9)

ax.set_xlim(0.01, 300)
plt.savefig(OUT_DIR / "fig17_pipeline_latency_breakdown.png")
plt.close()
print("Generated fig17_pipeline_latency_breakdown.png")

