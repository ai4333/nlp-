from .theme import PANEL, hud


def _chip(text, cls=""):
    return f'<span class="chip {cls}">{text}</span>'


def _crop(img, bbox, pad=260):
    if img is None:
        return None
    H, W = img.shape[:2]
    x0, y0, x1, y1 = bbox
    a, b = max(0, x0 - pad), max(0, y0 - pad)
    c, d = min(W, x1 + pad), min(H, y1 + pad)
    if c <= a or d <= b:
        return None
    vis = cv2.cvtColor(img[b:d, a:c], cv2.COLOR_GRAY2BGR)
    cv2.rectangle(vis, (x0 - a, y0 - b), (x1 - a, y1 - b), (40, 120, 255), 4)
    return vis


def _render_card(card: dict, img):
    # the display moment: a light, large tag, the way the reference sets its
    # headline — this is the one thing on the screen that should feel big
    st.markdown(f'<div class="display">{card["tag"]}</div>'
                f'<div class="display-sub">{card["name"]}</div>',
                unsafe_allow_html=True)

    chips = _chip(card["category"])
    if card["zone"]:
        chips += _chip(f"sheet zone {card['zone']}", "g")
    if card["needs_review"]:
        chips += _chip("tag read with low confidence — confirm it", "d")
    if card["ambiguous"]:
        chips += _chip("tag has more than one reading", "d")
    st.markdown(f'<div class="chips">{chips}</div>', unsafe_allow_html=True)

    if card["what_it_is"]:
        st.markdown(f'<div class="card" style="margin-top:12px">'
                    f'<div class="kv">{card["what_it_is"]}</div></div>',
                    unsafe_allow_html=True)
    if card["why_it_matters"]:
        st.markdown(f'<div class="card" style="border-left:3px solid var(--warn)">'
                    f'<p class="eyebrow">On the job</p>'
                    f'<div class="kv">{card["why_it_matters"]}</div></div>',
                    unsafe_allow_html=True)

    for h in card["hazards"]:
        st.markdown(f'<div class="card" style="border-left:3px solid var(--bad)">'
                    f'<p class="eyebrow">Hazard · {h["class"]}</p>'
                    f'<div class="kv">{h["note"]}</div></div>', unsafe_allow_html=True)

    c1, c2 = st.columns([1, 1], gap="medium")
    with c1:
        if card["lines"]:
            st.markdown('<p class="eyebrow sp">Lines on it</p>', unsafe_allow_html=True)
            st.dataframe(pd.DataFrame([
                {"line": l["tag"], "size (in)": l.get("size_in") or "—",
                 "carries": (l.get("hazard") or {}).get("service", l.get("service", "")) ,
                 "hazard": (l.get("hazard") or {}).get("class", "—")}
                for l in card["lines"]]), hide_index=True, use_container_width=True)
        if card["flows_in_from"] or card["flows_out_to"]:
            st.markdown('<p class="eyebrow sp">Which way it flows</p>',
                        unsafe_allow_html=True)
            st.dataframe(pd.DataFrame(
                [{"direction": "in from", "tag": f["tag"], "what it is": f["name"],
                  "confidence": round(f["confidence"], 2), "why": f["because"]}
                 for f in card["flows_in_from"]] +
                [{"direction": "out to", "tag": f["tag"], "what it is": f["name"],
                  "confidence": round(f["confidence"], 2), "why": f["because"]}
                 for f in card["flows_out_to"]]),
                hide_index=True, use_container_width=True)
        if card["connected"]:
            st.markdown('<p class="eyebrow sp">Connected to</p>', unsafe_allow_html=True)
            st.dataframe(pd.DataFrame([
                {"tag": c["tag"], "what it is": c["name"], "type": c["category"]}
                for c in card["connected"]]), hide_index=True, use_container_width=True)
    with c2:
        if card["watched_by"]:
            st.markdown('<p class="eyebrow sp">Instruments on it</p>',
                        unsafe_allow_html=True)
            st.dataframe(pd.DataFrame([
                {"tag": i["tag"], "what it reads": i["name"]}
                for i in card["watched_by"]]), hide_index=True, use_container_width=True)
        if card["relief"]:
            st.markdown('<p class="eyebrow sp">Relief · never block these in</p>',
                        unsafe_allow_html=True)
            st.dataframe(pd.DataFrame([
                {"tag": r["tag"], "what it is": r["name"]} for r in card["relief"]]),
                hide_index=True, use_container_width=True)

    crop = _crop(img, card["bbox"])
    if crop is not None:
        st.markdown('<p class="eyebrow sp">Where it is on the drawing</p>',
                    unsafe_allow_html=True)
        st.image(crop, use_container_width=True,
                 caption=f'{card["tag"]} · zone {card["zone"]} · {card["sheet"]}')

    if card["unknowns"]:
        st.markdown('<p class="eyebrow sp">What this does NOT tell you</p>',
                    unsafe_allow_html=True)
        st.markdown('<div class="card" style="border-left:3px solid var(--tx3)">'
                    + "".join(f'<div class="kv">· {u}</div>' for u in card["unknowns"])
                    + "</div>", unsafe_allow_html=True)


def _render_plan(p: ISO.Plan):
    st.markdown(f'<div class="display">Isolating {p.target}</div>'
                f'<div class="display-sub">{p.target_name}</div>',
                unsafe_allow_html=True)
    if p.isolation_valves:
        st.markdown('<p class="eyebrow sp">Close these</p>', unsafe_allow_html=True)
        st.dataframe(pd.DataFrame([
            {"valve": v.tag, "what it is": v.name or "—", "hops from the item": v.hops,
             "reached through": " → ".join(v.via) if v.via else "directly"}
            for v in p.isolation_valves]), hide_index=True, use_container_width=True)
    else:
        st.error("No block valve was found on any branch of this item on this sheet.")

    if p.relief:
        st.markdown('<p class="eyebrow sp">Relief and blowdown — do NOT block in</p>',
                    unsafe_allow_html=True)
        st.dataframe(pd.DataFrame([{"tag": r.tag, "what it is": r.name}
                                   for r in p.relief]),
                     hide_index=True, use_container_width=True)
    if p.bleeds:
        st.markdown('<p class="eyebrow sp">Vent and drain points inside the isolation</p>',
                    unsafe_allow_html=True)
        st.markdown('<div class="kv">' + ", ".join(b.tag for b in p.bleeds) + "</div>",
                    unsafe_allow_html=True)
    if p.open_branches:
        st.markdown('<p class="eyebrow sp">Branches with no block valve on this sheet</p>',
                    unsafe_allow_html=True)
        st.dataframe(pd.DataFrame([
            {"branch reaches": b.tag, "what it is": b.name or "—", "hops": b.hops}
            for b in p.open_branches]), hide_index=True, use_container_width=True)

    st.markdown('<div class="card" style="border-left:3px solid var(--warn);margin-top:14px">'
                + "".join(f'<div class="kv">· {n}</div>' for n in p.notes)
                + "</div>", unsafe_allow_html=True)


def render(kg, sheet_id: str, img, entities: list[dict], generator=None,
           docstore=None):
    known = FIELD.sheet_tags(kg, sheet_id)
    size = (img.shape[1], img.shape[0]) if img is not None else None

    ask_panel = st.container(border=True)
    ask_panel.__enter__()
    st.markdown(PANEL + hud("Ask in plain English", "no jargon needed"),
                unsafe_allow_html=True)
    # A form so Enter always submits — same reliability fix as the workbench.
    with st.form(key=f"fld_form_{sheet_id}", clear_on_submit=True, border=False):
        fld_typed = st.text_input(
            "field", label_visibility="collapsed",
            placeholder="a tag like V-1101A · “what does SDV mean?” · "
                        "“which valves isolate P-1101A?”")
        go = st.form_submit_button("Ask", type="primary")
    if st.button("Clear", key="fld_clear"):
        st.session_state.pop("_fld_q", None)
        st.rerun()

    tagged = [e["tag"] for e in entities if e.get("tag")][:6]
    sugg = ["Explain this whole drawing"] \
        + ([f"What is {tagged[0]}?", f"Which valves isolate {tagged[0]}?"] if tagged else []) \
        + ["What does SDV mean?"]
    cols = st.columns(len(sugg))
    for i, s in enumerate(sugg):
        if cols[i].button(s, key=f"fld_s{i}", use_container_width=True):
            st.session_state["_fld_now"] = s

    ask_panel.__exit__(None, None, None)

    q = st.session_state.pop("_fld_now", None)
    if go and fld_typed and fld_typed.strip():
        q = fld_typed.strip()
    if q:
        st.session_state["_fld_q"] = q
        st.rerun()

    q = st.session_state.get("_fld_q")
    st.write("")

    # Entering the container explicitly keeps the long branch below at one
    # indent level; `with` here would mean re-indenting the whole answer tree.
    result_panel = st.container(border=True)
    result_panel.__enter__()
    st.markdown(PANEL, unsafe_allow_html=True)
    if not q:
        st.markdown('<div class="empty"><b>Type a tag, or just ask</b></div>',
                    unsafe_allow_html=True)
    else:
        kind = FIELD.route(q, kg, sheet_id, known)
        bare = K.strip_question(q)
        # a bare tag typed on its own is an item lookup
        if not kind and bare.upper() in known:
            kind, q2 = "item", f"What is {bare}?"
        else:
            q2 = q
        res = FIELD.answer(q2, kg, sheet_id, image_size=size, known_tags=known)

        st.markdown(f'<div class="kv" style="color:var(--tx3);margin-bottom:10px">'
                    f'“{q}” &nbsp;·&nbsp; answered by <b>{(res or {}).get("handler","the query engine")}</b>'
                    f'</div>', unsafe_allow_html=True)

        if res is None:
            # Not a field-shaped question — a count, a comparison, something
            # about the sheet as a whole. Sending the reader to another tab to
            # ask it again is a dead end; run it here instead. Field mode has
            # to answer whatever it is handed.
            if generator is None:
                st.info("That question needs the query engine, which is not "
                        "loaded here. Ask it on the Workbench tab.")
            else:
                from src.edi.qa.answer import ask, answer_stream
                with st.spinner("reading the drawing…"):
                    full = ask(q, kg, generator, sheet_id, image=img,
                               docstore=docstore, field_mode=False,
                               with_crops=False, stream_answer=True)
                brief = full["evidence"].get("briefing", "")
                if full["answer"]:
                    st.markdown(full["answer"])
                elif brief:
                    try:
                        st.write_stream(answer_stream(q, brief))
                    except Exception:
                        st.markdown(brief)
                if full.get("rows"):
                    with st.expander("The rows this came from"):
                        st.dataframe(pd.DataFrame(full["rows"],
                                                  columns=full["columns"] or None
                                                  ).astype(str),
                                     hide_index=True, use_container_width=True)
        elif res["handler"] == "overview":
            # Streamed so the reader watches the explanation being written.
            from src.edi.qa.answer import narrate_stream
            brief = res["evidence"].get("briefing") or res["answer"]
            try:
                st.write_stream(narrate_stream(q, brief))
            except Exception:
                st.markdown(brief)
            with st.expander("The facts this was written from"):
                st.markdown(brief)
        elif res["handler"] == "item":
            card = (res["evidence"].get("card") or {})
            if card:
                _render_card(card, img)
                st.markdown("---")
                if st.button(f"How do I isolate {card['tag']}?", key="fld_iso",
                             type="primary"):
                    st.session_state["_fld_now"] = f"which valves isolate {card['tag']}"
                    st.rerun()
            else:
                st.warning(res["answer"])
        elif res["handler"] == "item_question":
            # A real question that names an item. The card is the grounding;
            # the answer is written against what was actually asked, streamed
            # so the reader watches it appear.
            from src.edi.qa.answer import answer_stream
            brief = res["evidence"].get("briefing") or res["answer"]
            try:
                st.write_stream(answer_stream(q, brief))
            except Exception:
                st.markdown(brief)
            card = res["evidence"].get("card") or {}
            crop = _crop(img, card["bbox"]) if card.get("bbox") else None
            if crop is not None:
                st.image(crop, use_container_width=True,
                         caption=f'{card.get("tag","")} · zone {card.get("zone","")}')
            with st.expander("The facts this was written from"):
                st.markdown(brief)
            if card.get("tag") and st.button(f"Everything about {card['tag']}",
                                             key="fld_iq_card"):
                st.session_state["_fld_now"] = f"What is {card['tag']}?"
                st.rerun()

        elif res["handler"] == "isolation":
            p = res["evidence"].get("isolation")
            if p:
                plan = ISO.Plan(target=p["target"], target_name=p["target_name"],
                                isolation_valves=[ISO.Point(**v) for v in p["isolation_valves"]],
                                open_branches=[ISO.Point(**v) for v in p["open_branches"]],
                                bleeds=[ISO.Point(**v) for v in p["bleeds"]],
                                relief=[ISO.Point(**v) for v in p["relief"]],
                                crosses_sheet=p["crosses_sheet"], notes=p["notes"])
                _render_plan(plan)
            else:
                st.warning(res["answer"])
        elif res["handler"] == "flow":
            st.markdown(res["answer"])
            card = res["evidence"].get("card") or {}
            crop = _crop(img, card["bbox"]) if card.get("bbox") else None
            if crop is not None:
                st.image(crop, use_container_width=True,
                         caption=f'{card["tag"]} · zone {card["zone"]}')
            if st.button(f"Everything about {card.get('tag','it')}", key="fld_toitem"):
                st.session_state["_fld_now"] = f"What is {card.get('tag','')}?"
                st.rerun()
        else:
            st.markdown(res["answer"])
            info = res["evidence"].get("knowledge")
            if info and info.get("source") == "isa":
                st.caption(f"Decoded from ISA-5.1: {info.get('code','')} = "
                           f"{info.get('variable','')} · {info.get('function','')}"
                           + (f" · {info['modifier']}" if info.get("modifier") else ""))

    result_panel.__exit__(None, None, None)

    # ── the reference tables
    st.write("")
    lookup_panel = st.container(border=True)
    lookup_panel.__enter__()
    st.markdown(PANEL + hud("Look up a term", "ISA 5.1 · glossary"),
                unsafe_allow_html=True)
    t1, t2, t3 = st.tabs(["Plant glossary", "Tag letters (ISA-5.1)", "What is in the pipe"])
    with t1:
        term = st.text_input("gloss", label_visibility="collapsed",
                             placeholder="filter the glossary…", key="fld_gloss")
        rows = [{"term": k, "what it is": v[0], "why it matters on the job": v[1]}
                for k, v in sorted(G.GLOSSARY.items())
                if not term.strip() or term.lower() in k or term.lower() in v[0].lower()]
        st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True,
                     height=420)
    with t2:
        c1, c2 = st.columns(2)
        c1.markdown('<p class="eyebrow">First letter · what it measures</p>',
                    unsafe_allow_html=True)
        c1.dataframe(pd.DataFrame([{"letter": k, "measured variable": v}
                                   for k, v in sorted(ISA.FIRST.items())]),
                     hide_index=True, use_container_width=True, height=330)
        c2.markdown('<p class="eyebrow">Following letters · what it does</p>',
                    unsafe_allow_html=True)
        c2.dataframe(pd.DataFrame([{"letter": k, "function": v}
                                   for k, v in sorted(ISA.SUCCEEDING.items())]),
                     hide_index=True, use_container_width=True, height=330)
        st.dataframe(pd.DataFrame([
            {"tag": k, "what it is": v["name"], "in plain English": v["plain"]}
            for k, v in sorted(ISA.CONVENTION.items())]),
            hide_index=True, use_container_width=True, height=280)
    with t3:
        st.dataframe(pd.DataFrame([
            {"service code": k, "hazard": v[0], "what it means for you": v[1]}
            for k, v in sorted(G.SERVICE_HAZARD.items())]),
            hide_index=True, use_container_width=True, height=420)
    lookup_panel.__exit__(None, None, None)
