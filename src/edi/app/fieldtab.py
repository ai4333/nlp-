"""
Field mode — the screen for the person standing next to the equipment.

Everything else in this app is built for somebody who already reads P&IDs. This
screen is for the technician who does not: it takes a tag or a plain question
and answers in plain English, shows the piece of the drawing it is talking
about, lists what is connected, what watches it, what is in the pipes and what
that means for them — and then says explicitly what the drawing does NOT tell
them.

Nothing here is generated by a language model. Every line is either read out of
the graph or looked up in the knowledge layer. On a rig a fluent guess is worse
than "I don't know", so this screen is only allowed to say what it can prove.
"""
from __future__ import annotations

